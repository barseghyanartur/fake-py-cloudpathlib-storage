"""
Configuration hooks for `pytest`.

- Expose this checkout's `fakepy.cloudpathlib_storage` beneath fake.py's
  regular (non-namespace) `fakepy` package, so source-tree tests work.
- Replace the real cloudpathlib provider clients with their local
  counterparts (`LocalS3Client`, `LocalGSClient`, `LocalAzureBlobClient`),
  each rooted in a per-test temporary directory. This applies to unit
  tests and to documentation code blocks run by `pytest-codeblock`, so
  nothing ever talks to real AWS, Google Cloud or Azure.
- Clean up files generated by tests (including documentation tests) by
  calling the `clean_up` method of the `FILE_REGISTRY` instance.
"""

from pathlib import Path

import pytest
from cloudpathlib.local import (
    LocalAzureBlobClient,
    LocalGSClient,
    LocalS3Client,
)
from fake import FILE_REGISTRY

import fakepy

__author__ = "Artur Barseghyan <artur.barseghyan@gmail.com>"
__copyright__ = "2024-2026 Artur Barseghyan"
__license__ = "MIT"
__all__ = ("isolated_storage",)

# Expose the checkout beneath fake.py's regular parent package.
fakepy.__path__.insert(0, str(Path(__file__).parent / "fakepy"))


@pytest.fixture(autouse=True)
def isolated_storage(tmp_path, monkeypatch):
    """Route every storage to local clients in a temporary directory."""
    from fakepy.cloudpathlib_storage import (
        aws_s3,
        azure_cloud_storage,
        google_cloud_storage,
    )
    from fakepy.cloudpathlib_storage.cloud import LocalFileSystemStorage

    for module, name, cls in [
        (aws_s3, "S3Client", LocalS3Client),
        (google_cloud_storage, "GSClient", LocalGSClient),
        (azure_cloud_storage, "AzureBlobClient", LocalAzureBlobClient),
    ]:

        def factory(_cls=cls, **kwargs):
            if _cls is LocalAzureBlobClient:
                # The local Azure client requires a (dummy) connection string
                kwargs.setdefault("connection_string", "local-test")
            return _cls(local_storage_dir=tmp_path / _cls.__name__, **kwargs)

        monkeypatch.setattr(module, name, factory)

    original = LocalFileSystemStorage.__init__

    def init(self, *args, **kwargs):
        kwargs.setdefault("local_storage_dir", tmp_path / "local")
        original(self, *args, **kwargs)

    monkeypatch.setattr(LocalFileSystemStorage, "__init__", init)
    yield
    FILE_REGISTRY.clean_up()
